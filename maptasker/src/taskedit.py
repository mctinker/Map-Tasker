"""taskedit: build an editable model of a Task and save it as a standalone .tsk.xml file.

Edit Task: edit an existing Task's name/priority and the values of arguments its
actions already have in the XML. Never touches PrimeItems.xml_tree -- all edits
happen on a deep copy, and the only output is a new standalone file.

Add Task: create a brand-new Task and populate it with newly-synthesized actions.
Only actions whose arguments are all plain numbers/text/checkboxes (or the purely
informational 'Output Variables' Bundle hint) can be synthesized from scratch --
see classify_action_addability() for the exact rule. A third-party plugin action
whose only obstacle was its opaque payload <Bundle> qualifies too: bundles.json
(generated by bldbndle.py from a real backup, keyed by the same action_codes key)
supplies that payload -- see get_bundle_definition/_synthesize_bundle_arg. Never
touches the live tree either; a new Task exists only in memory until saved.

This module is the editor itself: loading a Task, creating one, adding, removing, copying and
moving its actions.  The rest is split by responsibility:

    taskedit_model      EditableArg / EditableAction / EditableTask and the codes they share
    taskedit_args       building the editable arguments of an action from its XML
    taskedit_addable    which actions can be added from scratch, and synthesizing their arguments
    taskedit_apply      validating and applying what a user typed (arguments, labels, If conditions)
    taskedit_save       writing a Task out -- file, device, live tree -- and deleting one
"""

from __future__ import annotations

import copy
import time
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from xml.etree.ElementTree import Element

    from maptasker.src.primitem import RunState

from maptasker.src import sessundo
from maptasker.src.actionc import action_codes
from maptasker.src.editcommon import set_child_text as _set_child_text
from maptasker.src.taskedit_addable import build_synthesized_args, classify_action_addability, synthesize_if_condition
from maptasker.src.taskedit_args import build_editable_action, build_editable_actions
from maptasker.src.taskedit_model import (
    ELSE_ACTION_CODE,
    END_IF_ACTION_CODE,
    IF_ACTION_CODE,
    IF_ACTION_KEY,
    IF_BLOCK_FOLLOWERS,
    EditableAction,
    EditableTask,
)


def resolve_task_by_name(task_name: str, state: RunState) -> tuple[str, Element] | None:
    """Look up a Task's id and live XML element by its displayed name.

    Returns (task_id, live_element), or None if not found. Callers must not mutate
    the returned element directly -- go through load_task_for_edit() instead.
    """
    entry = state.tasker_root_elements["all_tasks_by_name"].get(task_name)
    if entry is None:
        return None
    return entry["id"], entry["xml"]


def load_task_for_edit(task_name: str, state: RunState) -> EditableTask | None:
    """Resolve a Task by name, deep-copy it, and build its editable-action model.

    This is the one point of contact with the live tree -- everything downstream
    (including Save) operates on the copy, so the in-memory backup is never touched.
    """
    resolved = resolve_task_by_name(task_name, state=state)
    if resolved is None:
        return None
    task_id, live_element = resolved
    task_copy = copy.deepcopy(live_element)
    return EditableTask(
        task_id=task_id,
        task_element=task_copy,
        actions=build_editable_actions(task_copy, state=state),
    )


def load_task_for_edit_by_id(task_id: str, state: RunState) -> EditableTask | None:
    """load_task_for_edit, but from the id the XML actually stores.

    A Scene's Task bindings (<keyTask>, <clickTask>, ...) hold an id, not a name, and the
    name in the tables is not always the Task's own: taskerd gives an unnamed Task a
    made-up display name built from its first action, which is not something to look a
    Task up by and definitely not something to write back into its <nme>.  Going through
    the id skips both problems.

    Same contract as load_task_for_edit otherwise -- a deep copy, so nothing downstream
    touches the live tree until apply_edited_task_to_live_tree.
    """
    entry = state.tasker_root_elements.get("all_tasks", {}).get(str(task_id))
    if entry is None:
        return None
    task_copy = copy.deepcopy(entry["xml"])
    return EditableTask(
        task_id=str(task_id),
        task_element=task_copy,
        actions=build_editable_actions(task_copy, state=state),
    )


# How far above the loaded file's highest Task/Profile id the first id this program hands out
# lands.  A backup is a snapshot, and the device goes on numbering after it is taken: a Task or
# Profile made on the phone since then takes the next id up.  Measured on 2026-09-11: a backup
# whose highest id was 1208, and a device that had since made Profile 1210 -- so 1209, which
# highest + 1 handed to a new Task, was already spoken for there.  Two imports of the 'Test'
# Project carried a new Task under 1209 (once as 'Atest1Plus', once as 'Test1plus'); both times
# the edited 'Test1' that calls it arrived and the new Task did not.
#
# Above the file's highest rather than in one of its gaps, because the gaps are what Tasker's
# own import renumbering fills: the 'Atest1' Profile imported that same day came back as 1144,
# the lowest id free in the backup.  An id is an identity, not a count, so the jump costs
# nothing, and 1000 is headroom for a very busy phone.
NEW_OBJECT_ID_HEADROOM = 1000


def next_unique_task_or_profile_id(reserved: set[str] | None = None, *, state: RunState) -> int:
    """Computes the next id safe to assign to a brand-new Task or Profile.

    Never lower than NEW_OBJECT_ID_HEADROOM above the highest id the file had when it was
    loaded (PrimeItems.loaded_highest_object_id), so the first new object sits clear of ids
    the device may have handed out since the backup was taken.  The ones after it follow on
    one by one, since by then they are the highest in use.  Nothing loaded from a file (0)
    means no floor.

    `reserved` is ids that are spoken for but not in the tables yet -- Tasks composed but
    not created.  The Scene Properties Event tabs can have one in progress under each of
    their three sub-tabs at once (see guiwins_sceneprops._render_scene_event_new_task), and without
    this they would all be handed the same id: registering the second would then overwrite
    the first in all_tasks, leaving the first event's binding silently pointing at the other
    Task's actions.

    Real Tasker backups keep Task and Profile ids collision-free with each other
    -- confirmed empirically against this repo's own sample backup (zero overlap
    across 792 Task ids and 267 Profile ids) -- which strongly suggests Tasker
    draws both from one running counter, not two independent ones. Drawing from
    the union of both tables here, rather than each type's own table alone (the
    previous behavior of create_new_task/profedit.create_new_profile), guarantees
    they can never hand out the same id to a Task and a Profile even if both
    tables happen to share the same current max.

    Does NOT need to consider all_projects: real Tasker Project ids are UUIDs
    (see projedit.create_new_project), a completely different format that can't
    collide with a small integer by construction.
    """
    existing_ids = [
        int(k)
        for table_name in ("all_tasks", "all_profiles")
        for k in state.tasker_root_elements.get(table_name, {})
        if k.isdigit()
    ]
    existing_ids.extend(int(k) for k in (reserved or ()) if str(k).isdigit())
    loaded_highest = state.loaded_highest_object_id
    floor = loaded_highest + NEW_OBJECT_ID_HEADROOM + 1 if loaded_highest else 0
    return max(max(existing_ids, default=0) + 1, floor)


def create_new_task(
    name: str, priority: str, reserved_ids: set[str] | None = None, *, state: RunState
) -> EditableTask | str:
    """Build a brand-new Task element, not tied to any existing one, ready for
    actions to be added to it. Returns an error message string if no backup is
    loaded -- needed both to generate a collision-free id and to source the correct
    Element class (see write_standalone_task_xml's note on class mismatches).

    `reserved_ids` is passed straight to next_unique_task_or_profile_id -- the ids of any
    other Task built by this same call site and not registered yet; see there for what goes
    wrong without it.
    """
    if state.xml_root is None:
        return "Load a Tasker backup file first (Add Task needs it to generate a unique Task ID)."

    new_id = next_unique_task_or_profile_id(reserved_ids, state=state)

    element_cls = type(state.xml_root)
    task_element = element_cls("Task", {"sr": f"task{new_id}"})

    now_millis = str(int(time.time() * 1000))
    for tag, text in (
        ("cdate", now_millis),
        ("edate", now_millis),
        ("id", str(new_id)),
        ("nme", name.strip()),
        ("pri", priority.strip() or "100"),
    ):
        child = element_cls(tag)
        child.text = text
        task_element.append(child)

    return EditableTask(task_id=str(new_id), task_element=task_element, actions=[])


def add_action_to_task(
    edited_task: EditableTask, action_key: str, position: int | None = None, *, state: RunState
) -> EditableAction | list[str]:
    """Synthesize a new Action element from scratch and add it to the task --
    appended at the end by default (position=None), or inserted at `position`
    (0-based, among the task's other actions -- clamped to a valid index) if
    given, so a caller can place it before or after a specific existing
    action instead of always at the end. See build_edit_task_dialog's own
    "Add an action" section, which offers exactly that choice; Add Task's
    picker always appends (position=None) since there's nothing to insert
    relative to until the user's already added something.

    Re-checks addability even though the UI shouldn't offer a non-addable action --
    defense in depth, matching apply_edits_to_task's list[str]-errors convention.
    """
    addable, reason = classify_action_addability(action_key, state=state)
    if not addable:
        return [reason or f"'{action_key}' is not addable."]

    code = action_key[:-1]
    action_code = action_codes[action_key]
    effective_args = action_codes[action_code.redirect].args if action_code.redirect else action_code.args

    act_number = len(edited_task.actions)
    element_cls = type(edited_task.task_element)

    action_element = element_cls("Action", {"sr": f"act{act_number}", "ve": "7"})
    code_element = element_cls("code")
    code_element.text = code
    action_element.append(code_element)

    if action_key == IF_ACTION_KEY:
        args = synthesize_if_condition(element_cls, action_element)
    else:
        # action_key lets build_synthesized_args rebuild a plugin payload <Bundle>
        # from bundles.json's definition for this very code -- see get_bundle_definition.
        args = build_synthesized_args(element_cls, action_element, effective_args, action_key, state=state)

    edited_task.task_element.append(action_element)

    new_action = EditableAction(
        action_element=action_element,
        act_number=act_number,
        code=code,
        action_name=action_code.name,
        args=args,
    )
    if position is None:
        edited_task.actions.append(new_action)
    else:
        edited_task.actions.insert(max(0, min(position, len(edited_task.actions))), new_action)
        _renumber_actions(edited_task)
    return new_action


def add_if_block_to_task(
    edited_task: EditableTask, variant: str, position: int | None = None, *, state: RunState
) -> EditableAction | list[str]:
    """Insert an "If" action plus whatever companions the chosen variant calls
    for (see IF_BLOCK_VARIANTS): nothing extra for "If", an "End If" after it
    for "If, End If", or an "Else" then an "End If" for "If, Else, End If" --
    all as consecutive actions starting at `position` (same semantics as
    add_action_to_task's: None appends at the end).

    Returns the "If" action itself on success (the companions need no further
    attention -- they're arg-less), or a list of error strings, matching
    add_action_to_task's convention.
    """
    if_action = add_action_to_task(edited_task, IF_ACTION_KEY, position, state=state)
    if isinstance(if_action, list):
        return if_action

    insert_at = edited_task.actions.index(if_action) + 1
    for follower_key in IF_BLOCK_FOLLOWERS.get(variant, ()):
        follower = add_action_to_task(edited_task, follower_key, insert_at, state=state)
        if isinstance(follower, list):
            return follower
        insert_at += 1
    return if_action


def action_display_levels(actions: list[EditableAction]) -> list[int]:
    """Per-action If-nesting depth for indenting a Task's action list in the
    Add/Edit Task dialogs: every action after an "If" sits one level deeper;
    "Else" and "End If" render at their encapsulating "If"'s own level, with
    "End If" also popping back out so anything after it returns to the outer
    level. Nested "If"s stack a level each. An unbalanced "Else"/"End If"
    clamps at level 0 rather than going negative -- a Task's actions are free
    text as far as Tasker is concerned, so malformed nesting must still render.
    """
    levels = []
    depth = 0
    for action in actions:
        if action.code in (ELSE_ACTION_CODE, END_IF_ACTION_CODE):
            levels.append(max(depth - 1, 0))
        else:
            levels.append(depth)
        if action.code == IF_ACTION_CODE:
            depth += 1
        elif action.code == END_IF_ACTION_CODE:
            depth = max(depth - 1, 0)
    return levels


def _renumber_actions(edited_task: EditableTask) -> None:
    """Renumber every action's sr="actN" (and its act_number) to match its current
    position in edited_task.actions -- shared by remove/copy/move so the model and
    the XML always agree on order. XML child order is irrelevant to Tasker; it
    orders Actions by the numeric suffix of sr="actN", not document order (Tasker
    itself writes them out-of-order in the file -- see build_editable_actions), so
    this is the only bookkeeping a reorder needs.
    """
    for new_number, action in enumerate(edited_task.actions):
        action.action_element.set("sr", f"act{new_number}")
        action.act_number = new_number


def remove_action_from_task(edited_task: EditableTask, act_number: int) -> None:
    """Remove an action (by its current act_number) from both the XML and the
    model, then renumber every remaining action's sr="actN" contiguously from 0 in
    their current order.
    """
    target = next((a for a in edited_task.actions if a.act_number == act_number), None)
    if target is None:
        return

    edited_task.task_element.remove(target.action_element)
    edited_task.actions = [a for a in edited_task.actions if a is not target]

    _renumber_actions(edited_task)


def copy_action_in_task(edited_task: EditableTask, act_number: int, state: RunState) -> EditableAction | None:
    """Duplicate the action currently numbered act_number, inserting the copy
    immediately after it in the model, then renumber every action's sr="actN" to
    match (XML child order doesn't matter -- see _renumber_actions).

    Returns the new (copied) action, or None if act_number wasn't found.
    """
    source_index = next((i for i, a in enumerate(edited_task.actions) if a.act_number == act_number), None)
    if source_index is None:
        return None

    source = edited_task.actions[source_index]
    new_element = copy.deepcopy(source.action_element)
    edited_task.task_element.append(new_element)

    new_action = build_editable_action(new_element, source.act_number, state=state)
    edited_task.actions.insert(source_index + 1, new_action)

    _renumber_actions(edited_task)
    return new_action


def move_action_in_task(edited_task: EditableTask, act_number: int, new_position: int) -> bool:
    """Move the action currently numbered act_number to new_position (0-based,
    among the task's other actions), then renumber every action's sr="actN" to
    match (XML child order doesn't matter -- see _renumber_actions).

    new_position is clamped to a valid index. Returns True if the move was
    performed, False if act_number wasn't found.
    """
    source_index = next((i for i, a in enumerate(edited_task.actions) if a.act_number == act_number), None)
    if source_index is None:
        return False

    new_position = max(0, min(new_position, len(edited_task.actions) - 1))
    action = edited_task.actions.pop(source_index)
    edited_task.actions.insert(new_position, action)

    _renumber_actions(edited_task)
    return True


def is_action_enabled(action: EditableAction) -> bool:
    """Whether this Action is enabled -- mirrors action.py's own display logic,
    which treats an <on> child as "disabled" (Tasker always writes it as
    <on>false</on> when present) and its absence as "enabled". Same shape as
    profedit.is_profile_enabled for a Profile's <limit>.
    """
    on = action.action_element.find("on")
    return on is None or on.text != "false"


def set_action_enabled(edited_task: EditableTask, act_number: int, enabled: bool) -> None:
    """Enables or disables the action currently numbered act_number by removing/
    setting its <on> child -- applied immediately (not staged), same as
    profedit.set_profile_enabled. Takes act_number rather than an EditableAction
    (and looks it up itself), matching remove/copy/move_action_in_task's own
    calling convention -- the GUI's per-action buttons only close over act_number.
    """
    action = next((a for a in edited_task.actions if a.act_number == act_number), None)
    if action is None:
        return

    if enabled:
        on = action.action_element.find("on")
        if on is not None:
            action.action_element.remove(on)
    else:
        _set_child_text(action.action_element, "on", "false")


def action_can_fail(action: EditableAction) -> bool:
    """Whether Tasker considers this action able to fail (actionc.py's canfail
    flag) -- only such actions get the 'Continue Task After Error' checkbox;
    the flag is meaningless on ones that can't error.
    """
    action_code = action_codes.get(f"{action.code}t")
    return action_code is not None and action_code.canfail == "True"


def action_continues_after_error(action: EditableAction) -> bool:
    """Whether this action carries <se>false</se> ('Continue Task After
    Error') -- the same child action.py's get_extra_stuff reads for display.
    No <se> (or any other text) means Tasker's default: stop the Task on error.
    """
    se = action.action_element.find("se")
    return se is not None and se.text == "false"


def set_action_continue_after_error(
    edited_task: EditableTask,
    act_number: int,
    continue_after_error: bool,
) -> None:
    """Sets or clears an action's <se>false</se> by writing/removing the <se>
    child -- applied immediately (not staged), same convention as
    set_action_enabled's <on> handling: Tasker omits the element entirely for
    the default (stop on error), so unchecking removes it rather than writing
    <se>true</se>.
    """
    action = next((a for a in edited_task.actions if a.act_number == act_number), None)
    if action is None:
        return

    if continue_after_error:
        _set_child_text(action.action_element, "se", "false")
    else:
        se = action.action_element.find("se")
        if se is not None:
            action.action_element.remove(se)


# What a Task with no Project shows as in the picker's Project column and filter.  Same
# words tasks.get_project_for_solo_task uses for the same state, so the two agree.
NO_PROJECT_NAME = "No Project"


def list_pickable_tasks(state: RunState) -> list[dict]:
    """Every Task that can be pointed at, with the Project that owns it.

    The Task-side counterpart of list_addable_actions, and shaped like it so one picker can
    render either: {"name", "project_name", "task_id"}, sorted by name.

    NOT MEMOIZED, unlike the action list.  That one caches because deciding whether an
    action is addable is expensive; this is two dict walks, and it has to be live -- a Task
    added through the Add Task dialog has to appear in the picker the moment it exists.

    A Task in more than one Project is listed once, under the first that claims it, which is
    what get_project_for_solo_task does too.  An unnamed Task is offered under the display
    name taskerd gave it ("Flash hello.269 (Unnamed)"), because that is the name every other
    Task pulldown in this app offers and the one legacy_task_id_for_name resolves.

    A BLANK name is skipped.  It should not occur -- taskerd invents that display name for
    exactly this reason -- but every caller of this list picks a Task BY NAME, so a row with
    no name is a row that does nothing when it is clicked.  Leaving it out is better than
    offering it and silently ignoring the click.
    """
    root = state.tasker_root_elements
    project_of: dict[str, str] = {}
    for project in root.get("all_projects", {}).values():
        for task_id in project_task_ids(project["xml"]):
            project_of.setdefault(task_id.strip(), project["name"])

    rows = [
        {
            "name": name,
            "task_id": str(entry["id"]),
            "project_name": project_of.get(str(entry["id"]), NO_PROJECT_NAME),
        }
        for name, entry in root.get("all_tasks_by_name", {}).items()
        if name
    ]
    rows.sort(key=lambda row: row["name"].lower())
    return rows


def search_pickable_tasks(query: str = "", project_name: str = "All", *, state: RunState) -> list[dict]:
    """Filter the Task list by name substring and/or exact Project name -- the Task-side
    search_addable_actions, matching on the same terms so both pickers behave alike.
    """
    query = query.strip().lower()
    rows = list_pickable_tasks(state=state)
    if query:
        rows = [row for row in rows if query in row["name"].lower()]
    if project_name and project_name != "All":
        rows = [row for row in rows if row["project_name"] == project_name]
    return rows


def apply_task_rename(edited_task: EditableTask, new_name: str, state: RunState) -> list[str]:
    """Validate a new Task name on its own and, only if valid, write it into the
    Task copy's <nme>. Returns [] on success, else the error messages, mutating
    nothing on error.

    Mirrors projedit.apply_edits_to_project's shape rather than
    apply_edits_to_task's: one field, and -- unlike that one, which validates
    the whole dialog and deliberately says nothing about other Tasks' names --
    a rename has to range over them, since two Tasks sharing a name would
    collide on the all_tasks_by_name key (see rename_task_in_live_tree) and
    make the Task pulldown ambiguous.

    A no-op rename (new_name unchanged) is allowed through -- a Task isn't a
    conflict with itself.
    """
    new_name = new_name.strip()
    current_name = edited_task.task_element.findtext("nme", "")

    errors = []
    if not new_name:
        errors.append("Task name cannot be empty.")
    elif new_name != current_name and task_name_exists(new_name, state=state):
        errors.append(f"A Task named '{new_name}' already exists in this backup. Choose a different name.")

    if errors:
        return errors

    _set_child_text(edited_task.task_element, "nme", new_name)
    return []


def rename_task_in_live_tree(edited_task: EditableTask, state: RunState) -> str:
    """Renames an already-registered Task in the in-memory backup: stamps the new
    <nme> onto the element the Task tables actually point at, and moves its
    all_tasks_by_name entry to the new key (all_tasks is keyed by id, which a
    rename doesn't change -- see register_new_task). Returns the previous name
    ("" if the Task isn't registered, in which case nothing is done -- defense in
    depth; the GUI only ever passes a Task just loaded via load_task_for_edit).

    Deliberately renames in place instead of swapping the edited copy into the
    tables the way apply_edited_task_to_live_tree does. That swap is right for Ok/
    Save, which commit the whole dialog, but wrong for Rename: the copy also
    carries any action Add/Copy/Move/Delete already performed in the dialog (those
    mutate it as they're clicked, unlike the argument fields, which are only read
    at Ok/Save time), so swapping it in would quietly commit that half-finished
    action editing as a side effect of renaming. Touching only <nme> keeps Rename
    to exactly what it says, and leaves everything else pending until the user
    commits it.

    The element written to is whatever all_tasks holds -- for a Task straight from
    the backup that IS the live tree's own element (taskerd.move_xml_to_table never
    deep-copies), and for one already committed via Ok it's that earlier copy.
    Either way it's the object maputil2.write_full_backup_to_current_file splices
    into the saved file, so the new name survives a save; updating only the table's
    "name" field would leave the written XML still carrying the old one.
    """
    with sessundo.undoable(f"Rename Task to '{edited_task.task_element.findtext('nme', '')}'", state=state):
        all_tasks = state.tasker_root_elements.get("all_tasks", {})
        entry = all_tasks.get(edited_task.task_id)
        if entry is None:
            return ""

        old_name = entry["name"]
        new_name = edited_task.task_element.findtext("nme", "") or old_name
        live_element = entry["xml"]
        _set_child_text(live_element, "nme", new_name)
        entry["name"] = new_name

        all_tasks_by_name = state.tasker_root_elements.setdefault("all_tasks_by_name", {})
        if old_name in all_tasks_by_name and old_name != new_name:
            del all_tasks_by_name[old_name]
        all_tasks_by_name[new_name] = {"xml": live_element, "id": edited_task.task_id}
        return old_name


def task_name_exists(name: str, state: RunState) -> bool:
    """Whether a Task with this name already exists in the currently loaded backup."""
    return name.strip() in state.tasker_root_elements.get("all_tasks_by_name", {})


def project_task_ids(project_element: Element) -> list[str]:
    """A Project's <tids> as a list of Task ids ([] if it owns none) -- the read
    half of profedit.add_task_to_project's append-dedup.
    """
    tids_element = project_element.find("tids")
    return tids_element.text.split(",") if tids_element is not None and tids_element.text else []
