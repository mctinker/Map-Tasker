def _build_default_arg(arg) -> EditableArg | None:
    """Seed a default EditableArg for a brand-new action being synthesized (Add Task).

    Returns None for any Bundle-category arg -- on an addable action (see
    classify_action_addability) the only Bundle that can appear is the informational
    'Output Variables' hint, which is safe to omit entirely (no row, no element
    written) -- and for any other unsupported category (defense in depth; the action
    shouldn't have been offered as addable if this is reached). The returned arg's
    `element` is left None -- add_action_to_task() builds and attaches the real XML
    element afterward, keeping this function pure/schema-only.
    """
    category = PrimeItems.tasker_arg_specs.get(arg.arg_type, "")
    if category == "Bundle":
        return None

    widget_kind, backing_tag, dropdown_options = _classify_arg_widget(arg)
    if widget_kind == "readonly":
        return None

    if widget_kind in ("checkbox", "dropdown"):
        current_value = "0"
    else:  # "text" or "raw_fallback"
        current_value = "0" if backing_tag == "Int" else ""

    return EditableArg(
        arg_id=arg.arg_id,
        arg_name=_display_arg_name(arg),
        widget_kind=widget_kind,
        backing_tag=backing_tag,
        is_var=False,
        element=None,
        current_value=current_value,
        dropdown_options=dropdown_options,
    )


def get_bundle_definition(action_key: str) -> dict | None:
    """The <Bundle> definition recorded in bundle.py for an action_codes key, or None.

    bundle.py (generated by bldbndle.py from a real Tasker backup) is keyed exactly
    like action_codes -- the numeric code plus "e" (Event), "s" (State) or "t"
    (Task Action) -- so '192s' or '2078e' looks up directly. Its value is
    {"Bundle": {attributes and sub-tags}}; this returns the inner dictionary, which
    is what _build_bundle_element rebuilds the xml from.
    """
    definition = bundles.get(action_key)
    return definition.get("Bundle") if definition else None


def needs_tasker_configuration(element: defusedxml.ElementTree.Element) -> bool:
    """Whether an Action/Event/State element carries a plugin payload <Bundle>, and
    so has to be configured inside Tasker rather than here.

    Detected by the payload's BLURB (see BLURB_TAG), which only a real third-party
    plugin Bundle has -- the informational 'Output Variables' hint doesn't. Works
    the same for an element read from a backup (its BLURB holds whatever that
    plugin was set to) and for one just synthesized from bundle.py (its BLURB is
    blank), which is exactly the distinction the warning exists to convey.
    """
    return any(descendant.tag == BLURB_TAG for bundle in element.iter("Bundle") for descendant in bundle.iter())


def tasker_configuration_warning(element: defusedxml.ElementTree.Element, name: str) -> str:
    """The warning to show for a plugin Action/condition, or "" when it needs none.

    Shared by the Edit Task/Edit Profile dialogs (a standing warning on the item's
    own panel) and by their add handlers (a notification as it is added) so both
    say the same thing -- see needs_tasker_configuration.
    """
    return PLUGIN_CONFIGURATION_WARNING.format(name=name) if needs_tasker_configuration(element) else ""


def _is_plugin_bundle_arg(arg) -> bool:
    """Whether an ArgumentCode is an opaque third-party plugin payload Bundle, as
    opposed to the informational 'Output Variables' Bundle hint (which needs no
    element written at all -- see _build_default_arg).
    """
    category = PrimeItems.tasker_arg_specs.get(arg.arg_type, "")
    return category == "Bundle" and arg.arg_name != OUTPUT_VARIABLES_ARG_NAME


def _unescape_bundle_text(text: str) -> str:
    """Decode a bundle.py text value back into the characters it stands for.

    bundle.py holds text in its xml source form, entity references and all (see
    bldbndle.escape_xml_text) -- '&lt;' there means a '<' character. The element
    tree escapes on the way out, so the text handed to it has to be the decoded
    characters or every '&' would be written back doubled ('&amp;lt;'). '&amp;'
    is decoded last, exactly reversing the order it was escaped in, so a value
    holding a literal '&lt;' survives the round trip intact.
    """
    return text.replace("&lt;", "<").replace("&gt;", ">").replace("&amp;", "&")


def _build_bundle_element(
    element_cls: type,
    tag: str,
    definition: dict | str,
) -> defusedxml.ElementTree.Element:
    """Rebuild an xml element from a bundle.py definition, recursively.

    A definition is either a string (a leaf element's text) or a dictionary whose
    entries are that element's attributes (_BUNDLE_ATTRIBUTE_NAMES) and sub-tags;
    a repeated sub-tag is held as a list of definitions.
    """
    element = element_cls(tag)
    if isinstance(definition, str):
        element.text = _unescape_bundle_text(definition)
        return element

    for name, value in definition.items():
        if name == _BUNDLE_TEXT_KEY:
            element.text = _unescape_bundle_text(value)
        elif name in _BUNDLE_ATTRIBUTE_NAMES and isinstance(value, str):
            element.set(name, value)
        elif isinstance(value, list):
            for repeated in value:
                element.append(_build_bundle_element(element_cls, name, repeated))
        else:
            element.append(_build_bundle_element(element_cls, name, value))

    return element


def _synthesize_bundle_arg(
    element_cls: type,
    container_element: defusedxml.ElementTree.Element,
    effective_args: list,
    action_key: str,
) -> EditableArg | None:
    """Build a plugin payload <Bundle> from bundle.py's definition for action_key,
    append it to container_element, and return a read-only EditableArg for it.

    Written before any of the action_codes arguments, so the element order matches
    the <Bundle sr="arg0"> then <Str sr="arg1">... that Tasker itself writes.

    The payload keeps the 'sr' it was recorded with rather than being renumbered
    from the ArgumentCode that declared it: the two disagree in real backups (event
    2078's payload is arg0 in the xml but arg1 in actionc.py), and the xml is the
    authority on where Tasker expects it. Falls back to the declaring argument's own
    id for the handful of recorded bundles that carry no 'sr' at all.

    Returns None when there is no recorded definition -- the code shouldn't have
    been offered as addable in that case (see classify_action_addability), so this
    just leaves the Bundle out rather than writing a malformed one.

    The payload itself is not editable here: it's the plugin's own configuration
    blob, seeded with the values a real backup used, and is meant to be configured
    in Tasker on the device.  Read-only args are skipped by validate_arg_values and
    apply_arg_values, so the row is purely informational.
    """
    definition = get_bundle_definition(action_key)
    if definition is None:
        return None

    bundle_element = _build_bundle_element(element_cls, "Bundle", definition)
    declaring_arg = next((arg for arg in effective_args if _is_plugin_bundle_arg(arg)), None)
    if not bundle_element.attrib.get("sr") and declaring_arg is not None:
        bundle_element.set("sr", f"arg{declaring_arg.arg_id}")
    container_element.append(bundle_element)

    sr = bundle_element.attrib.get("sr", "")
    return EditableArg(
        arg_id=sr[len("arg") :] if sr.startswith("arg") else "0",
        # A plugin payload argument usually has no name of its own in actionc.py --
        # fall back to the wording classify_action_addability uses for one.
        arg_name=(_display_arg_name(declaring_arg) if declaring_arg is not None else "") or "Plugin Payload",
        widget_kind="readonly",
        backing_tag="Bundle",
        is_var=False,
        element=bundle_element,
        current_value="(plugin configuration)",
        readonly_note="Configure this in Tasker on the Android device.",
    )


def _build_merged_plugin_arg(arg) -> EditableArg | None:
    """Seed a default EditableArg for an action_codes argument that is declared as a
    Bundle but is *not* the payload slot bundle.py just filled.

    _build_default_arg would drop it (a Bundle has no generic default), which would
    lose a real argument: event 2078 declares only one argument, its Bundle, yet the
    xml Tasker writes for it is <Bundle sr="arg0"> *plus* <Str sr="arg1"> -- the
    payload and the argument are two different elements. Text/Str is what Tasker
    writes for these, so that is what gets seeded.
    """
    if arg.arg_name == OUTPUT_VARIABLES_ARG_NAME:
        return None  # Informational hint, not an argument -- see _build_default_arg.

    return EditableArg(
        arg_id=arg.arg_id,
        arg_name=_display_arg_name(arg),
        widget_kind="text",
        backing_tag="Str",
        is_var=False,
        element=None,
        current_value="",
    )


def build_synthesized_args(
    element_cls: type,
    container_element: defusedxml.ElementTree.Element,
    effective_args: list,
    action_key: str = "",
) -> list[EditableArg]:
    """Synthesizes default Int/Str XML elements for a set of ArgumentCode
    definitions, appends them to container_element, and returns their bound
    EditableArgs.

    Public (not underscore-prefixed): shared by add_action_to_task (a new Task
    Action) and profedit.add_event_condition_to_profile (a new Profile Event
    condition) -- both build brand-new elements from the exact same Bundle/
    Int/Str argument shape (see build_editable_args' own docstring on why
    Profile conditions reuse this machinery). Skips any arg _build_default_arg
    returns None for (the informational 'Output Variables' Bundle hint, or an
    unsupported category -- shouldn't occur on an addable action/event; see
    classify_action_addability).

    action_key is the action_codes key being synthesized (e.g. '104t', '192s',
    '2078e'). Given one, a plugin payload Bundle is written first, rebuilt from
    bundle.py's recorded definition (see _synthesize_bundle_arg) -- that is what
    makes the plugin-based Actions/Events/States addable at all. Left empty, no
    Bundle is written; both callers pass it, so that is only a safe default rather
    than a used one.

    The payload is *merged with* the action_codes arguments, not substituted for
    them: bundle.py contributes the <Bundle>, then every argument actionc.py
    declares is synthesized alongside it, exactly as Tasker's own xml carries both.
    Only the one argument slot the payload itself occupies is left out, since the
    <Bundle> already fills it -- and even that slot is decided by the payload's own
    'sr' rather than by actionc.py, which disagrees with the xml for some codes.
    """
    args = []
    bundle_sr = ""
    if action_key:
        bundle_arg = _synthesize_bundle_arg(element_cls, container_element, effective_args, action_key)
        if bundle_arg is not None:
            args.append(bundle_arg)
            bundle_sr = f"arg{bundle_arg.arg_id}"

    for arg in effective_args:
        if bundle_sr and f"arg{arg.arg_id}" == bundle_sr:
            continue  # The <Bundle> written above already occupies this slot.

        # Any *other* Bundle-declared argument is a real argument of the plugin, which
        # Tasker writes as a plain <Str> -- _build_default_arg would drop it entirely.
        if bundle_sr and _is_plugin_bundle_arg(arg):
            editable_arg = _build_merged_plugin_arg(arg)
        else:
            editable_arg = _build_default_arg(arg)
        if editable_arg is None:
            continue

        if editable_arg.backing_tag == "Int":
            element = element_cls("Int", {"sr": f"arg{arg.arg_id}", "val": editable_arg.current_value or "0"})
        elif editable_arg.backing_tag in ("App", "Img"):
            # An empty <App>/<Img>, exactly as Tasker writes one for an action whose app or
            # icon has not been chosen yet.  've="2"' is what every <App sr="conN"> and
            # <Img> in a real backup carries; the argument forms of <App> carry no ve at
            # all, so only the <Img> gets one.  deviceinv fills in the children on save.
            attributes = {"sr": f"arg{arg.arg_id}"}
            if editable_arg.backing_tag == "Img":
                attributes["ve"] = "2"
            element = element_cls(editable_arg.backing_tag, attributes)
        else:  # "Str"
            element = element_cls("Str", {"sr": f"arg{arg.arg_id}", "ve": "3"})
            element.text = ""
        container_element.append(element)
        editable_arg.element = element
        args.append(editable_arg)
    return args


_SAFE_CATEGORIES = ("Int", "Str", "String", "Boolean")
# The two refusals that are not permanent.  Every other reason classify_action_addability
# gives is a statement about the action ("this plugin's payload can't be generated"); these
# two are statements about what is loaded right now, and both have the same way out -- a
# fetch from the device -- which the GUI offers wherever it shows either of these exact
# texts (see guiwins._render_inventory_fetch).  The icon one has a way out because an app's
# own icon is a package and a launcher activity, which is precisely what the Application
# fetch brings back: see deviceinv._merged_with_device_icons, and the module docstring
# there for the two icon kinds no fetch can reach.  Named constants rather than literals so
# that recognising one is an equality check against a definition, not a substring guess.
NO_APPS_REASON = "No Applications were found in the loaded configuration to choose from."
NO_ICONS_REASON = "No icons were found in the loaded configuration to choose from."
# The arg_specs.json categories an <Img> backs.  'Icon' is the one Task actions and Profile
# Events declare; 'Img' is proginit.py's own added spec, used by Scene elements.  Both are
# the same element and the same picker, so both are named wherever one is.
_ICON_CATEGORIES = ("Icon", "Img")


def classify_action_addability(action_key: str) -> tuple[bool, str]:
    """Whether a real numeric Task-action key (e.g. '104t') can be synthesized from
    scratch, and why not if not.

    Only args that are plain numbers/text/checkboxes, the informational 'Output
    Variables' Bundle hint, or an opaque plugin payload Bundle that bundle.py has a
    recorded definition for (see get_bundle_definition -- build_synthesized_args
    rebuilds the payload from it rather than having to invent one), can be safely
    synthesized; anything else (App/Icon/Image pickers, or a plugin payload nothing
    has recorded a definition for) has no generic default. Code '37' (If) has no
    args at all (action_codes["37t"].args == []) and would otherwise fall through
    the "not effective_args" case below as addable -- it gets its own synthesizer
    instead (see add_action_to_task's IF_ACTION_KEY branch and
    _synthesize_if_condition), building its <ConditionList>/<Condition> from
    IF_CONDITION_OPERATORS rather than the generic Bundle/Int/Str model, so it's
    left to fall through here too.

    Keyed by the raw action_codes key regardless of its t/s/e suffix, so it serves
    Task Actions ('...t') and Edit Profile's Event/State conditions ('...e'/'...s')
    alike -- bundle.py is keyed the same way.
    """
    action_code = action_codes[action_key]
    if action_code.redirect:
        target = action_codes.get(action_code.redirect)
        if target is None:
            return False, "Unresolvable action definition."
        effective_args = target.args
    else:
        effective_args = action_code.args

    if not effective_args:
        return True, ""

    for arg in effective_args:
        category = PrimeItems.tasker_arg_specs.get(arg.arg_type, "")
        if category in _SAFE_CATEGORIES:
            continue
        if category == "Bundle" and arg.arg_name == OUTPUT_VARIABLES_ARG_NAME:
            continue
        # A plugin payload we have a recorded definition for is generatable after all.
        if category == "Bundle" and get_bundle_definition(action_key) is not None:
            continue
        # An Application or an icon is generatable while there is an inventory to pick one
        # from -- see deviceinv.py, and _classify_arg_widget, which gates the field itself
        # on the same answer.  This is what makes Launch App, Notify and the other 20
        # entries listed in app_icon_fetch_design.md addable at all.
        if category == "App" and deviceinv.have_apps():
            continue
        if category in _ICON_CATEGORIES and deviceinv.have_icons():
            continue
        if category == "App":
            return False, NO_APPS_REASON
        if category in _ICON_CATEGORIES:
            return False, NO_ICONS_REASON
        reason = (
            f"Requires a '{category or arg.arg_type}' value for "
            f"'{arg.arg_name or 'plugin payload'}' that this tool can't generate yet."
        )
        return False, reason

    return True, ""


_ADDABLE_ACTIONS_CACHE: list[dict] | None = None
_ADDABLE_ACTIONS_GENERATION = -1


def list_addable_actions() -> list[dict]:
    """All real numeric Task-action entries with their addability, memoized.

    Most of the underlying data (actionc.py, arg_specs.json, category_descriptions.json)
    is static for the process lifetime, but addability is not: an App or Icon argument is
    generatable only while deviceinv has an inventory, and loading a configuration is what
    produces one.  The memo therefore carries the inventory generation it was built under
    and rebuilds when that moves -- without it, the Add Action picker would go on showing
    'Launch App' greyed out, with a reason that stopped being true, until restart.
    """
    global _ADDABLE_ACTIONS_CACHE, _ADDABLE_ACTIONS_GENERATION  # noqa: PLW0603
    inventory_generation = deviceinv.generation()
    if _ADDABLE_ACTIONS_CACHE is not None and inventory_generation == _ADDABLE_ACTIONS_GENERATION:
        return _ADDABLE_ACTIONS_CACHE

    rows = []
    for key, action_code in action_codes.items():
        if not (key.endswith("t") and key[:-1].isdigit()):
            continue  # Not a real numeric Task-action code (e.g. Scene-widget entries).
        addable, reason = classify_action_addability(key)
        category_code = action_code.category
        category_name = "Uncategorized"
        if category_code and category_code.isdigit():
            category_name = PrimeItems.tasker_category_descriptions.get(int(category_code), "Uncategorized")
        rows.append(
            {
                "action_key": key,
                "code": key[:-1],
                "name": action_code.name,
                "category_name": category_name,
                "addable": addable,
                "reason": reason,
            },
        )
    rows.sort(key=lambda row: row["name"])
    _ADDABLE_ACTIONS_CACHE = rows
    _ADDABLE_ACTIONS_GENERATION = inventory_generation
    return rows


def search_addable_actions(query: str = "", category_name: str = "All") -> list[dict]:
    """Filter the memoized action list by name substring and/or exact category name."""
    query = query.strip().lower()
    rows = list_addable_actions()
    if query:
        rows = [r for r in rows if query in r["name"].lower()]
    if category_name and category_name != "All":
        rows = [r for r in rows if r["category_name"] == category_name]
    return rows


